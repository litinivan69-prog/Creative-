export function answeredBrandBrainKeys(assets: Array<{ description: string | null }>) {
  return new Set(assets.flatMap((asset) => {
    const match = asset.description?.match(/^brand_brain:([^:]+):answer$/);
    return match ? [match[1]] : [];
  }));
}
